// Generates src/lib/memberImages.ts for the cabinet page:
//  - memberImageBlur: tiny base64 JPEG per photo → instant blurred preview
//  - memberImageVariants: pre-optimized WebP sizes (400/800/1600) under
//    public/pfps-opt/ → cards use plain <img srcSet> and never touch
//    /_next/image (whose dev/prod optimizer can permanently wedge a cache
//    key when a request is aborted early — see issue #3).
//
// Run after adding/changing photos: pnpm images

import { mkdir, readdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const WIDTHS = [400, 800, 1600];

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const publicDir = path.join(root, "public");
const srcDir = path.join(publicDir, "pfps");
const outDir = path.join(publicDir, "pfps-opt");
const outFile = path.join(root, "src/lib/memberImages.ts");

const files = [];
async function walk(dir) {
	for (const entry of await readdir(dir, { withFileTypes: true })) {
		const full = path.join(dir, entry.name);
		if (entry.isDirectory()) {
			await walk(full);
		} else if (/\.(jpe?g|png|webp|avif)$/i.test(entry.name)) {
			files.push(full);
		}
	}
}
await walk(srcDir);
files.sort();

const blurRows = [];
const variantRows = [];
for (const file of files) {
	const rel = "/" + path.relative(publicDir, file).split(path.sep).join("/");
	const outRelDir = path.join(
		"pfps-opt",
		path.relative(srcDir, path.dirname(file))
	);
	const ext = path.extname(file);
	const base = path.basename(file, ext);

	const blur = await sharp(file)
		.rotate()
		.resize({ width: 20 })
		.jpeg({ quality: 30 })
		.toBuffer();
	blurRows.push(
		`\t${JSON.stringify(rel)}: "data:image/jpeg;base64,${blur.toString("base64")}",`
	);

	const urls = {};
	await mkdir(path.join(publicDir, outRelDir), { recursive: true });
	for (const width of WIDTHS) {
		const outPath = path.join(publicDir, outRelDir, `${base}-${width}.webp`);
		await sharp(file)
			.rotate()
			.resize({ width, withoutEnlargement: true })
			.webp({ quality: 80 })
			.toFile(outPath);
		urls[`w${width}`] = encodeURI(
			"/" +
				path.join(outRelDir, `${base}-${width}.webp`).split(path.sep).join("/")
		);
	}
	variantRows.push(
		`\t${JSON.stringify(rel)}: { ${WIDTHS.map((w) => `w${w}: ${JSON.stringify(urls[`w${w}`])}`).join(", ")} },`
	);
}

const out = `// Generated by scripts/member-images.mjs — do not edit by hand.
// Regenerate with: pnpm images

/** Tiny base64 JPEG previews, used as the blurred placeholder behind each photo. */
export const memberImageBlur: Record<string, string> = {
${blurRows.join("\n")}
};

/** Pre-optimized WebP variants (plain <img srcSet> sources), keyed by original path. */
export const memberImageVariants: Record<
	string,
	{ w400: string; w800: string; w1600: string }
> = {
${variantRows.join("\n")}
};
`;
await writeFile(outFile, out);
console.log(
	`Wrote ${blurRows.length} blur previews + ${variantRows.length} variant sets to ${path.relative(root, outFile)}`
);
